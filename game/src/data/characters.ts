const CHARACTER_ID_ALIASES: Record<string, string> = {
  adventurer: 'male-adventurer',
  female: 'female-person',
};

export function getCharacterById(id: string): CharacterDef {
  const characterId = CHARACTER_ID_ALIASES[id] ?? id;
  return CHARACTERS.find((character) => character.id === characterId) ?? CHARACTERS[0];
}
